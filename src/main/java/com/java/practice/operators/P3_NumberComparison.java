package com.java.practice.operators;

public class P3_NumberComparison {
	 public static void main(String[] args) {
	        int x = 15;
	        int y = 20;

	        System.out.println("x == y : " + (x == y));
	        System.out.println("x != y : " + (x != y));
	        System.out.println("x > y  : " + (x > y));
	        System.out.println("x < y  : " + (x < y));
	        System.out.println("x >= y : " + (x >= y));
	        System.out.println("x <= y : " + (x <= y));
	    }
}
